using PromptForge.Mac.Native;

namespace PromptForge.Mac.TextAccess;

/// <summary>
/// The general pasteboard (macOS clipboard). Text PromptForge puts there only to paste it is marked
/// transient and concealed (nspasteboard.org conventions), so clipboard managers don't record it.
/// Use on the UI thread.
/// </summary>
internal static class Pasteboard
{
    private const string TextType = "public.utf8-plain-text";
    private static readonly string[] PrivateMarkers = ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType"];

    /// <summary>Types password managers use to mark secrets they will clear from the clipboard on their own.</summary>
    internal static readonly HashSet<string> SensitiveMarkers = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];

    private static IntPtr General => ObjC.Send(ObjC.Class("NSPasteboard"), "generalPasteboard");

    /// <summary>Increments whenever any app changes the pasteboard.</summary>
    public static long ChangeCount
    {
        get
        {
            using var pool = new AutoreleasePool();
            return (long)ObjC.Send(General, "changeCount");
        }
    }

    /// <summary>Plain text on the pasteboard, or null when there is none.</summary>
    public static string? ReadText()
    {
        using var pool = new AutoreleasePool();
        return ObjC.ToManagedString(ObjC.Send(General, "stringForType:", ObjC.NSString(TextType)));
    }

    /// <summary>Puts text on the pasteboard normally, for when the user is meant to paste it themselves.</summary>
    public static void WriteText(string text)
    {
        using var pool = new AutoreleasePool();
        var pb = General;
        ObjC.Send(pb, "clearContents");
        ObjC.SendBool(pb, "setString:forType:", ObjC.NSString(text), ObjC.NSString(TextType));
    }

    /// <summary>Puts text on the pasteboard for our own paste, marked to stay out of clipboard history.</summary>
    public static void WritePrivateText(string text)
    {
        using var pool = new AutoreleasePool();
        var item = ObjC.Send(ObjC.Send(ObjC.Class("NSPasteboardItem"), "alloc"), "init");
        try
        {
            ObjC.SendBool(item, "setString:forType:", ObjC.NSString(text), ObjC.NSString(TextType));
            foreach (var marker in PrivateMarkers) ObjC.SendBool(item, "setData:forType:", ObjC.NSData([]), ObjC.NSString(marker));
            WriteItems([item]);
        }
        finally
        {
            ObjC.Send(item, "release");
        }
    }

    internal static void WriteItems(IEnumerable<IntPtr> items)
    {
        var pb = General;
        var array = ObjC.Send(ObjC.Class("NSMutableArray"), "array");
        foreach (var item in items) ObjC.Send(array, "addObject:", item);
        ObjC.Send(pb, "clearContents");
        if (!ObjC.SendBool(pb, "writeObjects:", array)) Log.Warn("pasteboard write failed");
    }

    public static async Task<bool> WaitForChangeAsync(long before, TimeSpan timeout)
    {
        var deadline = DateTime.UtcNow + timeout;
        while (DateTime.UtcNow < deadline)
        {
            if (ChangeCount != before) return true;
            await Task.Delay(15);
        }
        return ChangeCount != before;
    }
}

/// <summary>Saves and restores the user's pasteboard around our copy/paste round-trips.</summary>
internal sealed class PasteboardSnapshot
{
    /// <summary>Very large contents (e.g. a copied video) aren't held in memory; the user would only lose them if the size cap is hit.</summary>
    private const long MaxBytes = 128L * 1024 * 1024;

    private readonly List<List<(string Type, byte[] Data)>> _items;
    private bool _restored;

    private PasteboardSnapshot(List<List<(string, byte[])>> items) => _items = items;

    public static PasteboardSnapshot Capture()
    {
        using var pool = new AutoreleasePool();
        var items = new List<List<(string, byte[])>>();
        long total = 0;
        var pb = ObjC.Send(ObjC.Class("NSPasteboard"), "generalPasteboard");
        foreach (var item in ObjC.Items(ObjC.Send(pb, "pasteboardItems")))
        {
            var entries = new List<(string, byte[])>();
            foreach (var type in ObjC.Items(ObjC.Send(item, "types")))
            {
                var name = ObjC.ToManagedString(type);
                if (name is null) continue;
                var data = ObjC.ToBytes(ObjC.Send(item, "dataForType:", type));
                total += data.Length;
                if (total > MaxBytes)
                {
                    Log.Warn("clipboard too large to save completely");
                    break;
                }
                entries.Add((name, data));
            }
            if (entries.Count > 0) items.Add(entries);
        }
        return new PasteboardSnapshot(items);
    }

    public void Restore()
    {
        if (_restored) return;
        _restored = true;
        using var pool = new AutoreleasePool();
        var created = new List<IntPtr>();
        try
        {
            // A password manager clears its secret later only if the clipboard is still the entry it wrote.
            // Restoring would make a new entry it no longer recognises, leaving the password behind, so
            // concealed contents are cleared instead (the user can copy it again).
            if (_items.Any(entries => entries.Any(e => Pasteboard.SensitiveMarkers.Contains(e.Type))))
            {
                Log.Info("clipboard held concealed data; cleared instead of restored");
                ObjC.Send(ObjC.Send(ObjC.Class("NSPasteboard"), "generalPasteboard"), "clearContents");
                return;
            }
            foreach (var entries in _items)
            {
                var item = ObjC.Send(ObjC.Send(ObjC.Class("NSPasteboardItem"), "alloc"), "init");
                created.Add(item);
                foreach (var (type, data) in entries) ObjC.SendBool(item, "setData:forType:", ObjC.NSData(data), ObjC.NSString(type));
            }
            if (created.Count == 0) ObjC.Send(ObjC.Send(ObjC.Class("NSPasteboard"), "generalPasteboard"), "clearContents");
            else Pasteboard.WriteItems(created);
        }
        finally
        {
            foreach (var item in created) ObjC.Send(item, "release");
            _items.Clear(); // don't keep copies of the user's clipboard around
        }
    }
}
